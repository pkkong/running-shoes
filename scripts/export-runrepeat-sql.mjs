import { readFileSync } from "node:fs";
import vm from "node:vm";

const context = vm.createContext({ window: {} });
vm.runInContext(readFileSync(new URL("../data/runrepeat-reviews.js", import.meta.url), "utf8"), context);
const reviews = context.window.RUNNING_RUNREPEAT.reviews;
const prefix = process.env.SUPABASE_TABLE_PREFIX || "runfit_";
if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(`${prefix}shoes`)) throw new Error("Invalid table prefix");
const json = JSON.stringify(reviews, null, 2);
if (json.includes("$reviews$")) throw new Error("Invalid SQL delimiter in data");

process.stdout.write(`-- Generated by scripts/export-runrepeat-sql.mjs. No rows are deleted.
-- Applies only to exact existing models. Any mismatch rolls back all changes.
begin;
do $patch$
declare
  review jsonb;
  changed integer;
begin
  for review in select value from jsonb_array_elements($reviews$${json}$reviews$::jsonb)
  loop
    update public.${prefix}shoes
    set data = jsonb_set(data, '{runRepeatReview}', review, true), updated_at = now()
    where id = review->>'shoeId'
      and brand = review->>'brand'
      and model = review->>'model'
      and data->>'id' = review->>'shoeId'
      and data->>'brand' = review->>'brand'
      and data->>'model' = review->>'model';
    get diagnostics changed = row_count;
    if changed <> 1 then
      raise exception 'Exact model not found: %', review->>'shoeId';
    end if;
  end loop;
end;
$patch$;
commit;
`);
