import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const ROOT = process.cwd();
const context = { window: {} };

loadScript("data/shoes.js");
loadScript("data/lineup-history.js");
loadScript("data/price-queries.js");

const shoes = context.window.RUNNING_SHOES || [];
const history = context.window.RUNNING_LINEUP_HISTORY || {};
const priceQueryConfig = context.window.RUNNING_PRICE_QUERY_CONFIG || {};
const periods = history.periods || context.window.RUNNING_LINEUP_PERIODS || [];
const entries = history.entries || [];
const tablePrefix = normalizeTablePrefix(process.env.SUPABASE_TABLE_PREFIX);

if (!shoes.length) fail("No shoes loaded from data/shoes.js");
if (!periods.length) fail("No periods loaded from lineup history");
if (!entries.length) fail("No lineup entries loaded from lineup history");

const lines = [
  "-- Generated by scripts/export-supabase-seed.mjs",
  "-- Source of truth: data/shoes.js, data/lineup-history.js, data/price-queries.js",
  "begin;",
  `delete from public.${tableName("lineup_items")};`,
  `delete from public.${tableName("shoes")};`,
  `delete from public.${tableName("lineup_periods")};`,
  `delete from public.${tableName("price_query_config")};`,
  "",
];

periods.forEach((period, index) => {
  lines.push(
    `insert into public.${tableName("lineup_periods")} (id, label, sort_order, active, source_post_url, table_image_url, data) values (${sqlText(period.id)}, ${sqlText(period.label)}, ${index}, ${period.active ? "true" : "false"}, ${sqlText(period.sourcePostUrl || "")}, ${sqlText(period.tableImageUrl || "")}, ${sqlJson(period)}) on conflict (id) do update set label = excluded.label, sort_order = excluded.sort_order, active = excluded.active, source_post_url = excluded.source_post_url, table_image_url = excluded.table_image_url, data = excluded.data, updated_at = now();`
  );
});

lines.push("");

shoes.forEach((shoe, index) => {
  lines.push(
    `insert into public.${tableName("shoes")} (id, brand, model, display_name, category_group, category, sort_order, drop_mm, tags, image_url, image_source_url, official_product_url, data) values (${sqlText(shoe.id)}, ${sqlText(shoe.brand)}, ${sqlText(shoe.model)}, ${sqlNullableText(shoe.displayName)}, ${sqlText(shoe.categoryGroup)}, ${sqlText(shoe.category)}, ${index}, ${sqlNullableNumber(shoe.dropMm)}, ${sqlJson(shoe.tags || [])}, ${sqlNullableText(shoe.imageUrl)}, ${sqlNullableText(shoe.imageSourceUrl)}, ${sqlNullableText(shoe.officialProductUrl)}, ${sqlJson(shoe)}) on conflict (id) do update set brand = excluded.brand, model = excluded.model, display_name = excluded.display_name, category_group = excluded.category_group, category = excluded.category, sort_order = excluded.sort_order, drop_mm = excluded.drop_mm, tags = excluded.tags, image_url = excluded.image_url, image_source_url = excluded.image_source_url, official_product_url = excluded.official_product_url, data = excluded.data, updated_at = now();`
  );
});

lines.push("");

entries.forEach((entry, index) => {
  const [periodId, brand, category, models] = entry;
  lines.push(
    `insert into public.${tableName("lineup_items")} (period_id, brand, category, sort_order, models, data) values (${sqlText(periodId)}, ${sqlText(brand)}, ${sqlText(category)}, ${index}, ${sqlJson(models || [])}, ${sqlJson(entry)}) on conflict (period_id, brand, category) do update set sort_order = excluded.sort_order, models = excluded.models, data = excluded.data, updated_at = now();`
  );
});

lines.push(
  "",
  `insert into public.${tableName("price_query_config")} (id, data) values ('default', ${sqlJson(priceQueryConfig)}) on conflict (id) do update set data = excluded.data, updated_at = now();`,
  "",
  "commit;",
  ""
);

process.stdout.write(lines.join("\n"));

function loadScript(relativePath) {
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, relativePath), "utf8"), context, {
    filename: relativePath,
  });
}

function sqlJson(value) {
  return `${sqlText(JSON.stringify(value))}::jsonb`;
}

function sqlText(value) {
  return `'${String(value ?? "").replace(/'/g, "''")}'`;
}

function sqlNullableText(value) {
  if (value === null || value === undefined || value === "") return "null";
  return sqlText(value);
}

function sqlNullableNumber(value) {
  const number = Number(value);
  return Number.isFinite(number) ? String(number) : "null";
}

function normalizeTablePrefix(value) {
  const prefix = value === undefined ? "runfit_" : String(value);
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(`${prefix}table`)) {
    fail("Invalid SUPABASE_TABLE_PREFIX.");
  }
  return prefix;
}

function tableName(name) {
  return `${tablePrefix}${name}`;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
